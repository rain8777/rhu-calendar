const NORTH_IDS = TRANSPORT_NORTH_TEAMS.map((t) => t.id);
const SOUTH_IDS = TRANSPORT_SOUTH_TEAMS.map((t) => t.id);
NORTH_IDS.forEach((id) => { TEAM_COLORS[id] = "#9B2D30"; });
SOUTH_IDS.forEach((id) => { TEAM_COLORS[id] = "#2563EB"; });

export function getTeamColor(teamId) {
  return TEAM_COLORS[teamId] || "#8892b0";
}

export function getTeamName(teamId, teams) {
  const list = teams || TEAMS;
  const team = list.find((t) => t.id === teamId);
  return team ? team.name : teamId;
}

